/**
 * Native debug symbols inside the release bundle — ADR 0135, decision 8.
 *
 * The app's native libraries (Hermes, React Native, the Expo modules) are stripped in the bundle. With
 * `ndk.debugSymbolLevel` set, the Android Gradle Plugin also writes their symbol tables into the AAB, under
 * `BUNDLE-METADATA/com.android.tools.build.debugsymbols/`. Play reads them from there, so its crash reports name
 * functions rather than addresses, and nothing has to be uploaded separately. Phones get nothing more: Play strips the
 * metadata from what it installs.
 *
 * `SYMBOL_TABLE` and not `FULL`: function names are what a crash report needs, and the full DWARF data would make the
 * bundle much larger.
 *
 * `android/` is generated by `expo prebuild` on every build, so the line is written into the generated
 * `app/build.gradle` here. A template whose `defaultConfig` this cannot find fails the prebuild with a sentence, rather
 * than building a bundle without the symbols. `tools/verify/src/mobile-release.test.ts` runs it on a copy of the
 * template's block; the release workflow checks the built bundle holds them.
 */

const { withAppBuildGradle } = require('expo/config-plugins');

const LEVEL = 'SYMBOL_TABLE';
const LINE = `        ndk { debugSymbolLevel '${LEVEL}' }`;

/** The build file with the line added in `android { defaultConfig { … } }`, once. */
function addDebugSymbols(contents) {
  if (contents.includes(`debugSymbolLevel '${LEVEL}'`)) return contents;
  const anchor = /^(\s*)defaultConfig \{\n/m;
  if (!anchor.test(contents)) {
    throw new Error('debug-symbols: app/build.gradle has no defaultConfig block to add ndk.debugSymbolLevel to');
  }
  return contents.replace(anchor, (block) => `${block}${LINE}\n`);
}

function withDebugSymbols(config) {
  return withAppBuildGradle(config, (modConfig) => {
    if (modConfig.modResults.language !== 'groovy') {
      throw new Error(`debug-symbols: app/build.gradle is ${modConfig.modResults.language}, and this writes Groovy`);
    }
    modConfig.modResults.contents = addDebugSymbols(modConfig.modResults.contents);
    return modConfig;
  });
}

module.exports = withDebugSymbols;
module.exports.addDebugSymbols = addDebugSymbols;
module.exports.LEVEL = LEVEL;
